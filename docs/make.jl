# Builds the atlas site. Model pages are generated from each model's report.md,
# score.toml and figures/, so the site always shows what reproduce.jl last wrote.
using Documenter, QSPAtlas, TOML

const SRC = joinpath(@__DIR__, "src")
const GEN = joinpath(SRC, "models")
const ASSETS = joinpath(SRC, "assets", "models")
const ROOT = normpath(joinpath(@__DIR__, ".."))

rm(GEN; force = true, recursive = true)
rm(ASSETS; force = true, recursive = true)
mkpath(GEN)
mkpath(ASSETS)

const GRADE_TEXT = Dict(
    "A" => "runs and matches the published figures",
    "B" => "matches after documented fixes",
    "C" => "runs, does not match",
    "D" => "cannot run from published information",
)

scores = Dict{String, Any}()
for id in model_ids()
    dir = joinpath(models_dir(), id)
    sfile = joinpath(dir, "score.toml")
    isfile(sfile) && (scores[id] = TOML.parsefile(sfile))
    # figures
    figdir = joinpath(dir, "figures")
    if isdir(figdir)
        mkpath(joinpath(ASSETS, id))
        for f in readdir(figdir)
            # digitise_check images contain the published figure itself: never publish them
            endswith(f, ".png") && !startswith(f, "digitise_check") && cp(joinpath(figdir, f), joinpath(ASSETS, id, f); force = true)
        end
    end
    # page: report.md with figure links rewritten to the assets folder
    report = isfile(joinpath(dir, "report.md")) ? read(joinpath(dir, "report.md"), String) : "# $id\n\nNo report yet.\n"
    report = replace(report, r"\]\((\./)?figures/" => "](../assets/models/$id/")
    open(joinpath(GEN, "$id.md"), "w") do io
        println(io, report)
        # every figure the model produces, comparison plot first
        if isdir(figdir)
            figs = sort([f for f in readdir(figdir) if endswith(f, ".png") && !startswith(f, "digitise_check")];
                by = f -> (!startswith(f, "comparison"), f))
            if !isempty(figs)
                println(io, "\n## Figures\n")
                for f in figs
                    caption = startswith(f, "comparison") ?
                        "Simulation (blue) against points digitised from the paper's figure (black), per target curve" :
                        "Regenerated in the paper's layout: " * replace(f[1:(end - 4)], "_" => " ")
                    println(io, "![", caption, "](../assets/models/$id/", f, ")\n\n*", caption, ".*\n")
                end
            end
        end
        s = get(scores, id, nothing)
        if s !== nothing
            println(io, "\n## Score file\n\nGenerated by `reproduce.jl`; source: `models/$id/score.toml`.\n")
            for label in ("published", "fixed")
                run = get(s, label, Dict())
                isempty(run) && continue
                println(io, "\n**", run["label"], "**", run["ran"] ? "" : " (did not run: $(run["error"]))", "\n")
                println(io, "| curve | figure | RMS | P95 | tolerance (RMS / P95) | pass | coverage (reference / simulation, points) |")
                println(io, "|---|---|---|---|---|---|---|")
                # coverage is report-only (not part of the grade); older score files do not have it
                cov(c) = haskey(c, "coverage") ?
                    string(round(Int, 100 * c["coverage"]), " % / ", round(Int, 100 * get(c, "sim_coverage", 0.0)), " %, ", get(c, "n_points", "?")) : "n/a"
                for c in run["curves"]
                    println(io, "| `", c["id"], "` | ", c["figure"], " | ", c["rms"], " | ", c["p95"], " | ",
                        c["tol_rms"], " / ", c["tol_p95"], " | ", c["passed"] ? "yes" : "no", " | ", cov(c), " |")
                end
                println(io, "\nCoverage is the span of the digitised reference x values as a share of the axis, then the share of the axis on which the simulation is defined, and the number of reference points. It is reported only and does not change the grade.")
            end
        end
        println(io, "\n---\nSource: [`models/$id/`](https://github.com/singhharsh1708/QSPAtlas.jl/tree/main/models/$id)")
    end
end

npass(r) = (isempty(r) || !get(r, "ran", false)) ? "did not run" :
    string(count(c -> c["passed"], r["curves"]), " of ", length(r["curves"]))

# figures used on the home page
cp(joinpath(ROOT, "examples", "population_ouerdani.png"), joinpath(SRC, "assets", "population_ouerdani.png"); force = true)

# results table on the home page
let ids = sort(collect(keys(scores)))
    n = length(ids)
    counts = Dict(g => count(id -> scores[id]["grade"] == g, ids) for g in ("A", "B", "C", "D"))
    io = IOBuffer()
    println(io, "| model | paper | grade | strict grade | curves passing (as published / with fixes) | meaning |")
    println(io, "|---|---|---|---|---|---|")
    for id in ids
        s = scores[id]
        dagger = get(s, "inputs_from_target", false)
        println(io, "| [", id, "](models/", id, ".md) | [", s["citation"], "](https://doi.org/", s["doi"], ") | **",
            get(s, "grade_label", s["grade"]), "**", length(get(s, "figure_grades", Dict())) > 1 ?
                string(" (", join(["$k: $g" for (k, g) in sort(collect(s["figure_grades"]))], ", "), ")") : "",
            " | ", get(s, "grade_strict", "?"),
            " | ", npass(get(s, "published", Dict())), " / ", npass(get(s, "fixed", Dict())),
            " | ", GRADE_TEXT[s["grade"]],
            dagger ? "; some inputs not stated in the paper were read from the target figure" : "", " |")
    end
    table = String(take!(io))
    ndag = count(id -> get(scores[id], "inputs_from_target", false), ids)
    headline = string(counts["A"] + counts["B"], " of ", n, " reproduce (", counts["A"], " as published, ",
        counts["B"], " after documented fixes", ndag > 0 ? string(", ", ndag, " of those with inputs read from the figure (†)") : "",
        "); ", counts["C"], " run but do not match; ", counts["D"], " cannot be run from the published information.")
    tmpl = read(joinpath(@__DIR__, "index.template.md"), String)   # kept outside src/ so it is not published as a page
    write(joinpath(SRC, "index.md"), replace(tmpl, "{{HEADLINE}}" => headline, "{{TABLE}}" => table))
end


# Sensitivity tables: how each grade depends on the tolerance and on the gap-filling rule.
# Recomputed from the per-curve rms and p95 stored in score.toml, with the same grading
# rules as src/score.jl (A needs a matching published run without fills; B needs
# evidenced fixes; a :from_target fix gives a dagger).
let factors = (0.5, 0.67, 1.0, 1.5, 2.0), io = IOBuffer()
    function sens_grade(s, factor, figure = nothing)
        runs = Dict{String, Any}()
        for label in ("published", "fixed")
            run = get(s, label, Dict())
            isempty(run) && continue
            curves = [c for c in get(run, "curves", []) if figure === nothing || QSPAtlas.figure_key(
                QSPAtlas.ReferenceCurve(c["id"], "", [0.0], [0.0], QSPAtlas.Axis("x", "", :linear, 0, 1),
                    QSPAtlas.Axis("y", "", :linear, 0, 1), :curve, Dict{String, String}())) == figure]
            fixes = [f for f in get(run, "fixes", []) if figure === nothing || isempty(get(f, "figures", [])) || figure in f["figures"]]
            ok = get(run, "ran", false) && !isempty(curves) &&
                all(c -> c["rms"] <= factor * c["tol_rms"] && c["p95"] <= factor * c["tol_p95"], curves)
            runs[label] = (; ok, fixes, ran = get(run, "ran", false))
        end
        pub = get(runs, "published", nothing); fix = get(runs, "fixed", nothing)
        evid(fs) = all(f -> !isempty(strip(get(f, "evidence", ""))), fs)
        pub !== nothing && pub.ok && isempty(pub.fixes) && return "A"
        for r in (pub, fix)
            r !== nothing && r.ok && evid(r.fixes) && return string("B",
                any(f -> f["kind"] == "from_target", r.fixes) ? "†" : "",
                any(f -> get(f, "stage", "") == "after_comparison", r.fixes) ? "‡" : "")
        end
        return any(r -> r !== nothing && r.ran, (pub, fix)) ? "C" : "D"
    end
    println(io, "# Sensitivity of the grades\n")
    println(io, "Grades recomputed from the per-curve errors in each model's `score.toml`. The tolerance")
    println(io, "factor scales both thresholds (RMS 0.015 and P95 0.03 of the axis box). The strict grade")
    println(io, "counts only the article and its supplement as published information (see [Method](method.md)).\n")
    println(io, "## Model grades\n")
    println(io, "| model | strict grade | ", join(["tolerance x$(f)" for f in factors], " | "), " |")
    println(io, "|---|---|", join(fill("---", length(factors)), "|"), "|")
    for id in sort(collect(keys(scores)))
        s = scores[id]
        cells = [sens_grade(s, f) for f in factors]
        cells = [f == 1.0 ? "**$(c)**" : c for (f, c) in zip(factors, cells)]
        println(io, "| ", id, " | ", get(s, "grade_strict", "?"), " | ", join(cells, " | "), " |")
    end
    println(io, "\n## Figure grades\n")
    println(io, "| model | figure | ", join(["x$(f)" for f in factors], " | "), " | uses a value read from the figure |")
    println(io, "|---|---|", join(fill("---", length(factors)), "|"), "|---|")
    for id in sort(collect(keys(scores)))
        s = scores[id]
        for fig in sort(collect(keys(get(s, "figure_grades", Dict()))))
            cells = [sens_grade(s, f, fig) for f in factors]
            allfixes = vcat([get(get(s, label, Dict()), "fixes", []) for label in ("published", "fixed")]...)
            ft = any(f -> f["kind"] == "from_target" && (isempty(get(f, "figures", [])) || fig in f["figures"]), allfixes)
            println(io, "| ", id, " | ", fig, " | ", join(cells, " | "), " | ", ft ? "yes" : "no", " |")
        end
    end
    write(joinpath(SRC, "sensitivity.md"), String(take!(io)))
end

# copy benchmark and calibration outputs if present
for (sub, page) in (("solvers", "benchmarks.md"), ("calibration", "calibration.md"))
    d = joinpath(ROOT, "benchmarks", sub)
    out = joinpath(SRC, "assets", sub)
    rm(out; force = true, recursive = true)
    mkpath(out)
    isdir(joinpath(d, "results")) || continue
    for f in readdir(joinpath(d, "results"))
        any(endswith(f, e) for e in (".png", ".md", ".toml")) && !occursin("overlay", f) && cp(joinpath(d, "results", f), joinpath(out, f); force = true)
    end
end

# Solver benchmarks page, from benchmarks/solvers/results (written by benchmarks/solvers/run.jl)
let d = joinpath(ROOT, "benchmarks", "solvers", "results"), io = IOBuffer()
    println(io, "# Solver benchmarks\n")
    println(io, "Work-precision benchmarks of OrdinaryDiffEq solvers on the exact problems each model uses")
    println(io, "to reproduce its paper's figures. Error is the dense L2 error against a reference solution")
    println(io, "at tolerance 1e-12; time is the median of 5 solves. Solvers that cannot solve a problem")
    println(io, "within 100,000 steps at the loosest tolerance, or that need more than 5 s for that one solve,")
    println(io, "are listed as failed or too slow. Run with `julia --project=benchmarks/solvers benchmarks/solvers/run.jl`")
    println(io, "or with the Benchmarks workflow on GitHub Actions (one job per model, results as artifacts).\n")
    if isfile(joinpath(d, "summary.md"))
        println(io, read(joinpath(d, "summary.md"), String))
        for f in sort(readdir(d))
            endswith(f, ".png") && println(io, "\n### ", replace(f[1:(end - 4)], "__" => ": ", "_" => " "), "\n\n![](assets/solvers/", f, ")")
        end
    else
        println(io, "Results are not included in this build.")
    end
    write(joinpath(SRC, "benchmarks.md"), String(take!(io)))
end

