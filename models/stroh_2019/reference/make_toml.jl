# Generates digitise.toml (pixel boxes, tick calibrations, colours) for stroh_2019.
using TOML
MATLAB = Dict("blue"=>[0.0,0.447,0.741], "orange"=>[0.85,0.325,0.098], "yellow"=>[0.929,0.694,0.125],
              "purple"=>[0.494,0.184,0.556], "green"=>[0.466,0.674,0.188], "lblue"=>[0.301,0.745,0.933])
curves = Dict{String,Any}[]
function add!(id, fig, xaxis, yaxis, src, box, colour, xcal, ycal, yscale; excl = [], n = 60, tol = 0.40, kind = "curve", palette = ["blue","orange","yellow","purple","green"])
    d = Dict{String,Any}("image"=>String(split(src, " ")[1]), "id"=>id, "figure"=>fig, "xaxis"=>xaxis, "yaxis"=>yaxis, "source"=>src, "box"=>box,
        "colour"=>MATLAB[colour], "colour_name"=>colour, "xcal"=>xcal, "ycal"=>ycal, "xscale"=>"linear", "yscale"=>yscale,
        "n"=>n, "tol"=>tol, "kind"=>kind, "palette"=>palette)
    isempty(excl) || (d["exclude_boxes"] = excl)
    push!(curves, d)
end
src3 = "PSP4-8-676-g003.jpg (PMC6765697)"
src4 = "PSP4-8-676-g004.jpg (PMC6765697)"
# Figure 3 (monkey calibration lines)
f3 = [
 ("a", "3 mg/kg", [18,249,41,335], [49,0.0,288,25.0], [58,100.0,232.5,0.1], 500, [[17,95,243,335]],
    [("mAb00","blue","mAb0,0"),("M1S1","orange","Pb-Tx M1,S1"),("M2S2","green","Pb-Tx M2,S2"),("M1_0","lblue","Pb-Tx M1,0")]),
 ("b", "5 mg/kg", [16,248,409,703], [417.5,0.0,656.5,25.0], [73,100.0,232.5,0.1], 1200, [[15,75,545,704]],
    [("mAb00","blue","mAb0,0"),("M2S1","yellow","Pb-Tx M2,S1"),("M1S2","purple","Pb-Tx M1,S2")]),
 ("c", "10 mg/kg", [326,557,40,334], [48.5,0.0,287,25.0], [345,1000.0,543.5,0.1], 2500, [[325,410,240,335]],
    [("mAb00","blue","mAb0,0"),("M2S1","yellow","Pb-Tx M2,S1"),("M1S2","purple","Pb-Tx M1,S2")]),
]
for (p, dose, box, xc, yc, ymax, ex, cs) in f3, (k, col, nm) in cs
    add!("fig3$(p)_$(k)", "Figure 3$(p) ($dose), model line $nm, total drug in plasma", "time [day] linear -1 30",
         "total drug [nM] log 0.05 $ymax", src3, box, col, xc, yc, "log"; excl = ex, n = 60, palette = [c[2] for c in cs])
end
# Figure 4 (human projections, single 4.5 mg/kg dose)
names = [("mAb","blue","mAb0,0 (no mask)"),("10x","orange","10x mask"),("100x","yellow","100x mask"),("1000x","purple","1000x mask"),("10000x","green","10000x mask")]
tp = Dict("a"=>("plasma", [25,173,50,228], [49,0.0,229,60.0], [24.5,1000.0,174,1e-3], 286-237),
          "b"=>("periphery",[25,173,287,465],[286,0.0,466,60.0],[24.5,1000.0,174,1e-3],0),
          "c"=>("tumour",[25,173,524,702],[523,0.0,703,60.0],[24.5,1000.0,174,1e-3],0))
for p in ("a","b","c")
    (nm, box, xc, yc, _) = tp[p]
    for (k, col, lab) in names
        add!("fig4$(p)_$(k)", "Figure 4$(p), $nm total drug, $lab, human 4.5 mg/kg", "time [day] linear 0 60",
             "total drug [nM] log 1e-3 1e3", src4, box, col, xc, yc, "log"; n = 60)
    end
end
bt = Dict("d"=>("periphery receptor-mediated uptake [nmol]", [236,383,52,230], [51,0.0,231,60.0], [384,0.0,235,2000.0], "uptake [nmol] linear 0 2000"),
          "e"=>("tumour receptor-mediated uptake [nmol]", [236,383,289,467], [288,0.0,468,60.0], [384,0.0,235,15.0], "uptake [nmol] linear 0 15"))
for p in ("d","e")
    (nm, box, xc, yc, yax) = bt[p]
    for (k, col, lab) in names
        add!("fig4$(p)_$(k)", "Figure 4$(p), $nm, $lab, human 4.5 mg/kg", "time [day] linear 0 60", yax, src4, box, col, xc, yc, "linear"; n = 60)
    end
end
# Marker-contamination rule (added after review): the hollow observation markers share the line colours and are densest at
# t < 1 d (3-5 markers per sample time), so Figure 3 traces keep only t >= `min_x` = 1 d; every curve keeps only t >= 0 (no time before the dose).
for d in curves
    d["min_x"] = startswith(d["id"], "fig3") ? 1.0 : 0.0
end
for d in curves   # fig 3a: blue (mAb) and light blue (M1,0) differ by ~12 deg only, use tight windows
    if startswith(d["id"], "fig3a_")
        if d["colour_name"] == "blue"; d["hue"] = 209.0; d["hue_tol"] = 5.0; end
        if d["colour_name"] == "lblue"; d["hue"] = 197.0; d["hue_tol"] = 5.0; end
    end
end
open(joinpath(@__DIR__, "digitise.toml"), "w") do io
    println(io, "# Pixel boxes and tick calibrations for QSPAtlas stroh_2019 (generated by make_toml.jl; traced by digitise_stroh.jl)")
    println(io, "# Tick pixels (px, value pairs) were read from dark tick marks on each panel's frame; further ticks were used as checks (see report.md).")
    TOML.print(io, Dict("paper" => "stroh_2019", "curve" => curves); sorted = true)
end
println(length(curves), " curves")
